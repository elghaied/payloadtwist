import { buildThemePackage, themeNames, toThemeId } from './css'
import { presetTheme, THEME_PRESETS } from './presets'

/** Every built-in preset as a theme package, keyed by path relative to src/admin-themes/. */
export function adminThemeFiles(): Record<string, string> {
  const files: Record<string, string> = {}
  const presets = THEME_PRESETS.filter((p) => p.id !== 'payload')
  for (const preset of presets) {
    const pkg = buildThemePackage(presetTheme(preset), { id: preset.id, label: preset.name, description: preset.description })
    for (const [file, content] of Object.entries(pkg)) files[`${toThemeId(preset.id)}/${file}`] = content
  }
  const names = presets.map((p) => ({ id: toThemeId(p.id), ...themeNames(toThemeId(p.id)) }))
  files['index.ts'] =
    `// Generated by \`pnpm generate:admin-themes\` from payloadtwist's built-in presets — do not edit.\n` +
    names.map((n) => `import { ${n.manifest} } from './${n.id}'`).join('\n') +
    `\n\nexport const payloadtwistAdminThemes = [${names.map((n) => n.manifest).join(', ')}]\n`
  return files
}
