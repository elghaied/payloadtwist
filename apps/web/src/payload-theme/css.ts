import { buildComponentCss } from './components'
import { primaryFamily } from './controls'
import { GOOGLE_FONTS_CATALOG } from './google-fonts-catalog'
import { schema, TOKENS } from './schema'
import type { ThemeConfig } from './theme'

// Builds the CSS a user pastes into their Payload v4 project. Payload's styles live in
// `@layer payload-default`, so these unlayered rules win without !important.
//
// Cascade rules this file encodes:
// - Ramps are declared only on :root by Payload, so `html { --ramp-* }` reaches everything.
// - Payload re-declares semantic tokens on any element with [data-theme] (portaled menus,
//   popups), so overrides also target `html [data-theme='…']`, not just `html`.
// - An unlayered `html` override also wins in dark mode; for tokens Payload gives a separate
//   dark value, the dark block restates that value unless the user set their own.

const ORDER = new Map(schema.tokens.map((t, i) => [t.var, i]))
const byOrder = (a: string, b: string) => (ORDER.get(a) ?? 1e9) - (ORDER.get(b) ?? 1e9)

/** The dark-mode declarations needed so dark mode renders `theme.dark` (or Payload's dark defaults). */
export function darkDeclarations(theme: ThemeConfig): Record<string, string> {
  const light = lightDeclarations(theme)
  const out: Record<string, string> = {}
  for (const v of new Set([...Object.keys(light), ...Object.keys(theme.dark)])) {
    const t = TOKENS[v]
    if (!t || v.startsWith('--ramp-')) continue
    const withoutBlock = light[v] ?? t.dark ?? t.light
    const desired = theme.dark[v] ?? t.dark ?? light[v] ?? t.light
    if (desired !== withoutBlock) out[v] = desired
  }
  return out
}

/** Light declarations that differ from Payload's defaults (ramps first, then tokens). */
function lightDeclarations(theme: ThemeConfig): Record<string, string> {
  const out: Record<string, string> = {}
  for (const [v, value] of Object.entries(theme.ramps)) {
    if (TOKENS[v]?.light !== value) out[v] = value
  }
  for (const [v, value] of Object.entries(theme.light)) {
    if (TOKENS[v]?.light !== value) out[v] = value
  }
  return out
}

/** Every color token's dark-mode value (theme overrides first) — for components with dark contents. */
function darkColorTokens(theme: ThemeConfig): Record<string, string> {
  const out: Record<string, string> = {}
  for (const t of schema.tokens) {
    if (t.type !== 'color' || !t.dark || t.var.startsWith('--ramp-')) continue
    out[t.var] = theme.dark[t.var] ?? t.dark
  }
  return out
}

const GOOGLE_FAMILIES = new Set(GOOGLE_FONTS_CATALOG.map((f) => f.family))

export function googleFontsUrl(theme: ThemeConfig): string | null {
  const families = [
    ...new Set(Object.values(theme.controls.fonts ?? {}).map(primaryFamily)),
  ].filter((f) => GOOGLE_FAMILIES.has(f))
  if (!families.length) return null
  const params = families.map((f) => `family=${encodeURIComponent(f).replace(/%20/g, '+')}:wght@400;500;600;700`)
  return `https://fonts.googleapis.com/css2?${params.join('&')}&display=swap`
}

const block = (selector: string, decls: Record<string, string>) => {
  const keys = Object.keys(decls).sort(byOrder)
  if (!keys.length) return ''
  return `${selector} {\n${keys.map((k) => `  ${k}: ${decls[k]};`).join('\n')}\n}`
}

export interface BuildCssOptions {
  /** Root selector; `html` for custom.css, `html[data-admin-theme="id"]` for a theme package */
  scope?: string
  /** Include the explanatory header comment */
  header?: boolean
}

export function buildThemeCss(theme: ThemeConfig, { scope = 'html', header = true }: BuildCssOptions = {}): string {
  const fonts = googleFontsUrl(theme)
  const parts = [
    header
      ? `/*\n * Payload v4 admin theme — generated by payloadtwist (@payloadcms/ui ${schema.meta.payloadUiVersion})\n * Paste into your project's custom.css. No !important needed: Payload's styles are layered.\n */`
      : '',
    fonts ? `@import url('${fonts}');` : '',
    block(`${scope},\n${scope} [data-theme='light']`, lightDeclarations(theme)),
    block(`${scope}[data-theme='dark'],\n${scope} [data-theme='dark']`, darkDeclarations(theme)),
    buildComponentCss(theme.components ?? {}, scope, darkColorTokens(theme)),
    theme.customCss.trim(),
  ]
  return parts.filter(Boolean).join('\n\n') + '\n'
}

export function isDefaultTheme(theme: ThemeConfig): boolean {
  return buildThemeCss(theme, { header: false }).trim() === ''
}

// ─── Theme package (payload-admin-ui-themes) ───────────────────────────────

export interface ThemePackageOptions {
  id: string
  label: string
  description?: string
}

/** Kebab-case id that also yields valid JS identifiers (manifest/provider names) */
export const toThemeId = (name: string) => {
  const id = name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '') || 'my-theme'
  return /^\d/.test(id) ? `theme-${id}` : id
}

const pascal = (id: string) => id.replace(/(^|-)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase())

/** Exported names for a theme id: `light-cream` → lightCreamTheme / LightCreamThemeProvider */
export const themeNames = (id: string) => {
  const name = pascal(id)
  return { manifest: `${name.charAt(0).toLowerCase()}${name.slice(1)}Theme`, provider: `${name}ThemeProvider` }
}

export const ADMIN_THEMES_INSTALL = 'pnpm add payload-admin-ui-themes@npm:@zubricks/payload-admin-ui-themes'

/**
 * Files for `src/admin-themes/<id>/` of a user-selectable theme registered with `payload-admin-ui-themes`
 * (github.com/zubricks/payload-admin-ui-themes): CSS scoped to `html[data-admin-theme="id"]`,
 * a serializable manifest, and the client provider that imports the CSS.
 */
export function buildThemePackage(theme: ThemeConfig, opts: ThemePackageOptions): Record<string, string> {
  const id = toThemeId(opts.id)
  const { manifest, provider } = themeNames(id)
  const css = buildThemeCss(theme, { scope: `html[data-admin-theme="${id}"]`, header: false })
  const label = JSON.stringify(opts.label)
  return {
    'theme.css': `/* ${opts.label} — Payload v4 admin theme generated by payloadtwist */\n\n${css}`,
    'client.tsx': `'use client'\n\nimport './theme.css'\n\nexport function ${provider}({ children }: { children?: React.ReactNode }) {\n  return children\n}\n`,
    'index.ts': `import type { AdminUITheme } from 'payload-admin-ui-themes'\n\nexport const ${manifest}: AdminUITheme = {\n  id: ${JSON.stringify(id)},\n  label: ${label},\n  description: ${JSON.stringify(opts.description ?? 'Generated with payloadtwist')},\n  Provider: '@/admin-themes/${id}/client#${provider}',\n}\n`,
    'README.md': `# ${opts.label}

A Payload v4 admin theme generated by [payloadtwist](https://payloadtwist.com), packaged for
[payload-admin-ui-themes](https://github.com/zubricks/payload-admin-ui-themes): editors pick it from
their Settings menu next to Payload's own theme. Light and dark mode both work.

## Install

1. Install the plugin under the name its components expect:

   \`\`\`bash
   ${ADMIN_THEMES_INSTALL}
   \`\`\`

2. Copy this folder to \`src/admin-themes/${id}/\` (the manifest's \`Provider\` path uses the \`@/\` alias for \`src/\`).

3. Register it in \`payload.config.ts\`:

   \`\`\`ts
   import { payloadAdminUIThemes } from 'payload-admin-ui-themes'
   import { stockTheme } from 'payload-admin-ui-themes/themes/stock'
   import { ${manifest} } from './admin-themes/${id}'

   export default buildConfig({
     plugins: [
       payloadAdminUIThemes({
         themes: [stockTheme, ${manifest}],
         defaultTheme: '${id}',
         // This theme sets its own sizes; the plugin's density setting would override them
         density: false,
       }),
     ],
   })
   \`\`\`

4. Run \`pnpm payload generate:importmap\` and restart the dev server.

Every rule is scoped to \`html[data-admin-theme="${id}"]\`, so other installed themes are unaffected.
`,
  }
}
